package com.skyrpg.minions;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;

/**
 * One kind of minion (Cobblestone, Wheat, Zombie...), from {@code data/skyrpg_minions/skyrpg/minions/<type>.json}
 * (generated by {@code tools/skyblock/import_minions.py} from Hypixel's numbers).
 *
 * @param kind how it works: places and mines a block, plants and harvests a crop, grows and chops a tree, spawns and
 *             kills a mob, or fishes
 * @param block the block it places or the crop it plants ({@code BLOCK}, {@code CROP})
 * @param wood the tree it grows ({@code TREE}): "oak", "spruce"...
 * @param mob what it spawns ({@code MOB})
 * @param drops what one harvest gives
 * @param tiers tier 1 up; tier {@code n} is {@code tiers.get(n - 1)}
 */
public record MinionType(String id, String name, String category, Kind kind, Block block, String wood, EntityType<?> mob,
                         List<Drop> drops, List<Tier> tiers) {
    public enum Kind { BLOCK, CROP, TREE, MOB, FISHING }

    /** {@code min}-{@code max} of a SkyBlock item, with this chance (averages like 1.8 give 1 or 2). */
    public record Drop(String item, double min, double max, double chance) {
    }

    /**
     * @param item the SkyBlock id of the minion at this tier ("COBBLESTONE_GENERATOR_4")
     * @param actionSeconds time between actions
     * @param storage how many items it holds
     * @param cost what upgrading to this tier takes (SkyBlock id -> count), besides the minion itself
     */
    public record Tier(int tier, String item, double actionSeconds, int storage, Map<String, Integer> cost) {
        /** Storage slots (64 items each). */
        public int slots() {
            return Math.max(1, (storage + 63) / 64);
        }
    }

    public Tier tier(int tier) {
        return tiers.get(Math.max(1, Math.min(tier, tiers.size())) - 1);
    }

    public int maxTier() {
        return tiers.size();
    }

    /** "Cobblestone Minion IV". */
    public String title(int tier) {
        return name + " " + roman(tier);
    }

    public static String roman(int n) {
        String[] numerals = {"", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII"};
        return n > 0 && n < numerals.length ? numerals[n] : Integer.toString(n);
    }

    static MinionType parse(JsonObject json) {
        Kind kind = Kind.valueOf(json.get("kind").getAsString().toUpperCase(Locale.ROOT));
        Block block = json.has("block") ? BuiltInRegistries.BLOCK.getValue(Identifier.parse(json.get("block").getAsString())) : Blocks.AIR;
        EntityType<?> mob = json.has("mob") ? BuiltInRegistries.ENTITY_TYPE.getValue(Identifier.parse(json.get("mob").getAsString())) : null;
        List<Drop> drops = new ArrayList<>();
        for (JsonElement element : json.getAsJsonArray("drops")) {
            JsonObject d = element.getAsJsonObject();
            drops.add(new Drop(d.get("item").getAsString(), d.get("min").getAsDouble(), d.get("max").getAsDouble(), d.get("chance").getAsDouble()));
        }
        List<Tier> tiers = new ArrayList<>();
        for (JsonElement element : json.getAsJsonArray("tiers")) {
            JsonObject t = element.getAsJsonObject();
            Map<String, Integer> cost = new LinkedHashMap<>();
            if (t.has("cost")) {
                t.getAsJsonObject("cost").entrySet().forEach(e -> cost.put(e.getKey(), e.getValue().getAsInt()));
            }
            tiers.add(new Tier(t.get("tier").getAsInt(), t.get("item").getAsString(),
                    t.get("action").isJsonNull() ? 30 : t.get("action").getAsDouble(),
                    t.get("storage").isJsonNull() ? 64 : t.get("storage").getAsInt(), Map.copyOf(cost)));
        }
        return new MinionType(json.get("type").getAsString(), json.get("name").getAsString(),
                json.has("category") ? json.get("category").getAsString() : "other", kind, block,
                json.has("wood") ? json.get("wood").getAsString() : "oak", mob, List.copyOf(drops), List.copyOf(tiers));
    }
}

package com.skyrpg.skyblock;

import com.skyrpg.core.Features;
import com.skyrpg.core.net.OpenPage;
import com.skyrpg.hub.Hub;
import com.skyrpg.skyblock.area.Areas;
import com.skyrpg.skyblock.auction.AuctionHouse;
import com.skyrpg.skyblock.bazaar.Bazaar;
import com.skyrpg.skyblock.island.IslandRules;
import com.skyrpg.skyblock.island.Islands;
import com.skyrpg.skyblock.profile.ProfileCommands;
import com.skyrpg.skyblock.profile.ProfileListPayload;
import com.skyrpg.skyblock.profile.Profiles;
import com.skyrpg.skyblock.recipe.Crafting;
import com.skyrpg.skyblock.recipe.Recipes;
import com.skyrpg.skyblock.shop.SkyShops;
import com.skyrpg.skyblock.storage.StoragePayloads;
import com.skyrpg.skyblock.time.SkyBlockClock;
import com.skyrpg.skyblock.travel.FastTravel;
import com.skyrpg.skyblock.zone.Zones;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.command.v2.CommandRegistrationCallback;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry;
import net.fabricmc.fabric.api.networking.v1.ServerPlayConnectionEvents;
import net.minecraft.commands.Commands;
import net.minecraft.resources.Identifier;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * SkyRPG SkyBlock: Hypixel SkyBlock as a mod. Every SkyBlock item is an item definition in
 * {@code data/skyrpg_skyblock/skyrpg/items} (generated by {@code tools/skyblock/import_items.py}), a vanilla base
 * item carrying its SkyBlock id, so SkyBlock texture packs dress it as on Hypixel.
 */
public final class SkyRpgSkyblock implements ModInitializer {
    public static final String MOD_ID = "skyrpg_skyblock";
    public static final Logger LOGGER = LoggerFactory.getLogger(MOD_ID);

    @Override
    public void onInitialize() {
        // The survival Contracts and Journal quests have no place in SkyBlock (for now).
        Features.off(Features.CONTRACTS);
        Features.off(Features.QUESTS);
        Features.off(Features.ARTISAN_BENCH);
        Features.off(Features.SURVIVAL_LEVEL);
        Features.off(Features.SLAYER_SPAWNERS);
        // SkyBlock has no vanilla advancements to announce.
        net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents.SERVER_STARTED.register(server ->
                {
                    server.getGameRules().set(net.minecraft.world.level.gamerules.GameRules.SHOW_ADVANCEMENT_MESSAGES, false, server);
                    // Hypixel's mobs never break blocks (the Deep Caverns' Sneaky Creepers only hurt players).
                    server.getGameRules().set(net.minecraft.world.level.gamerules.GameRules.MOB_GRIEFING, false, server);
                });
        SkyblockItemUse.init();
        IslandRules.init();
        Deaths.init();
        Areas.init();
        SkyBlockClock.init();
        StoragePayloads.init();
        FastTravel.init();
        Zones.init();
        com.skyrpg.skyblock.fairy.FairySouls.init();
        com.skyrpg.skyblock.travel.LaunchPads.init();
        com.skyrpg.skyblock.travel.Lifts.init();
        com.skyrpg.skyblock.reforge.Reforging.init();
        com.skyrpg.skyblock.enchant.SkyEnchanting.init();
        com.skyrpg.skyblock.accessory.AccessoryBag.init();
        com.skyrpg.skyblock.pet.SkyBlockPets.init();
        com.skyrpg.skyblock.end.EndFeatures.init();
        com.skyrpg.skyblock.mining.Hotm.init();
        com.skyrpg.skyblock.mining.SkyMining.init();
        com.skyrpg.skyblock.sack.Sacks.init();
        com.skyrpg.skyblock.hollows.CrystalHollows.init();
        com.skyrpg.skyblock.gem.GemGrinderMenu.init();
        com.skyrpg.skyblock.ability.HypixelAbilities.init();
        com.skyrpg.skyblock.bestiary.Bestiary.init();
        com.skyrpg.skyblock.museum.Museum.init();
        com.skyrpg.skyblock.cookie.BoosterCookie.init();
        com.skyrpg.skyblock.fishing.SkyFishing.init();
        com.skyrpg.skyblock.experiment.Experiments.init();
        com.skyrpg.skyblock.alchemy.SkyBrewing.init();
        com.skyrpg.skyblock.quiver.Quiver.init();
        com.skyrpg.skyblock.essence.Essence.init();
        com.skyrpg.skyblock.dungeon.Catacombs.init();
        com.skyrpg.skyblock.crimson.CrimsonIsle.init();
        com.skyrpg.skyblock.garden.Garden.init();
        com.skyrpg.skyblock.rift.Rift.init();
        com.skyrpg.skyblock.galatea.Galatea.init();
        com.skyrpg.skyblock.mayor.Mayors.init();
        com.skyrpg.skyblock.festival.Festivals.init();
        com.skyrpg.skyblock.glacite.GlaciteTunnels.init();
        Recipes.init();
        Crafting.init();
        SkyShops.init();
        Bazaar.init();
        AuctionHouse.init();
        // The hub's portal leads to your island, not the survival world.
        Hub.setGate("Warping you to your island...", Islands::sendHome);
        // Profiles take over player data once the server is up (the overworld holds the profile list).
        ServerLifecycleEvents.SERVER_STARTED.register(Profiles::start);
        ServerLifecycleEvents.SERVER_STOPPED.register(server -> Profiles.stop());
        PayloadTypeRegistry.clientboundPlay().register(ProfileListPayload.TYPE, ProfileListPayload.CODEC);
        ServerPlayConnectionEvents.JOIN.register((handler, sender, server) -> ProfileListPayload.send(handler.player));
        CommandRegistrationCallback.EVENT.register((dispatcher, context, selection) -> {
            SbItemCommand.register(dispatcher);
            ProfileCommands.register(dispatcher);
            StoragePayloads.register(dispatcher);
            FastTravel.register(dispatcher);
            SkyShops.register(dispatcher);
            Bazaar.register(dispatcher);
            AuctionHouse.register(dispatcher);
            dispatcher.register(Commands.literal("sblevel").executes(ctx -> {
                OpenPage.send(ctx.getSource().getPlayerOrException(), id("leveling"));
                return 1;
            }));
        });
    }

    public static Identifier id(String path) {
        return Identifier.fromNamespaceAndPath(MOD_ID, path);
    }
}

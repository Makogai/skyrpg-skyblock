/**
 * Hypixel's NPC shops, from {@code data/skyrpg_skyblock/skyrpg/skyblock_shops/*.json} (generated by
 * {@code tools/skyblock/import_shops.py}): what each merchant sells, for coins and/or items. Every shop also buys
 * anything that has an NPC price (click an item in your inventory), and keeps your last sales to buy back. NPCs open a
 * shop with the {@code skyblock_shop} action ({@code {"shop": "farm_merchant"}}).
 */
public final class SkyShops {
    public static final String DIRECTORY = "skyrpg/skyblock_shops";
    /** Sales a player can buy back, newest first (Hypixel keeps the last ones until you leave). */
    public static final int BUYBACK = 9;

    /** One thing for sale: {@code count} of an item for {@code coins} and {@code costs} (other items). */
    public record Offer(String item, int count, long coins, Map<String, Integer> costs) {
    }

    public record Shop(Identifier id, String name, String island, List<Offer> offers) {
    }

    /** A sale that can be bought back for what it paid. */
    public record Sale(ItemStack stack, long price) {
    }

    private static Map<Identifier, Shop> shops = Map.of();
    private static final Map<UUID, Deque<Sale>> SALES = new ConcurrentHashMap<>();

    private SkyShops() {
    }

    public static void init() {
        JsonDataLoader.register(SkyRpgSkyblock.id("skyblock_shops"), DIRECTORY, SkyShops::load);
        Actions.register("skyblock_shop", (player, params) -> {
            Shop shop = find(params.has("shop") ? params.get("shop").getAsString() : "");
            if (shop != null) {
                ShopMenu.open(player, shop);
            } else {
                SkyRpgSkyblock.LOGGER.warn("No NPC shop {}", params);
            }
        });
    }

    private static void load(Map<Identifier, JsonElement> files) {
        Map<Identifier, Shop> loaded = new LinkedHashMap<>();
        files.forEach((id, element) -> {
            try {
                JsonObject json = element.getAsJsonObject();
                List<Offer> offers = new ArrayList<>();
                for (JsonElement entry : json.getAsJsonArray("offers")) {
                    JsonObject offer = entry.getAsJsonObject();
                    Map<String, Integer> costs = new LinkedHashMap<>();
                    if (offer.has("costs")) {
                        offer.getAsJsonObject("costs").entrySet().forEach(cost -> costs.put(cost.getKey(), cost.getValue().getAsInt()));
                    }
                    offers.add(new Offer(offer.get("item").getAsString(), Math.max(1, offer.get("count").getAsInt()),
                            offer.has("coins") ? offer.get("coins").getAsLong() : 0, Map.copyOf(costs)));
                }
                loaded.put(id, new Shop(id, json.get("name").getAsString(), json.has("island") ? json.get("island").getAsString() : "",
                        List.copyOf(offers)));
            } catch (RuntimeException e) {
                SkyRpgSkyblock.LOGGER.error("Skipping invalid shop {}: {}", id, e.getMessage());
            }
        });
        shops = loaded;
        SkyRpgSkyblock.LOGGER.info("Loaded {} NPC shops", loaded.size());
    }

    /** A shop by id ("farm_merchant" or "skyrpg_skyblock:farm_merchant"), or null. */
    public static Shop find(String id) {
        Identifier parsed = id.contains(":") ? Identifier.tryParse(id) : SkyRpgSkyblock.id(id);
        return parsed == null ? null : shops.get(parsed);
    }

    public static Map<Identifier, Shop> all() {
        return shops;
    }

    /** What an NPC pays for this stack: its NPC price times the count (0 if it can't be sold). */
    public static long sellPrice(ItemStack stack) {
        String id = SkyStacks.id(stack);
        return id == null ? 0 : (long) Math.floor(SkyStacks.npcPrice(id) * stack.getCount());
    }

    static Deque<Sale> sales(ServerPlayer player) {
        return SALES.computeIfAbsent(player.getUUID(), id -> new ArrayDeque<>());
    }

    static void forget(UUID player) {
        SALES.remove(player);
    }

    /** Buys an offer once, or as many times as make a stack ({@code max}) and fit and can be paid for. */
    static void buy(ServerPlayer player, Shop shop, int index, boolean max) {
        if (index < 0 || index >= shop.offers().size()) {
            return;
        }
        Offer offer = shop.offers().get(index);
        ItemDefinition def = ItemRegistry.skyblock(offer.item());
        if (def == null) {
            return;
        }
        ItemStack sample = SkyItems.create(def, 1);
        Inventory inventory = player.getInventory();
        int wanted = max ? Math.max(1, sample.getMaxStackSize() / offer.count()) : 1;
        int fits = room(inventory, sample) / offer.count();
        long affordable = offer.coins() > 0 ? Wallet.balance(player) / offer.coins() : Long.MAX_VALUE;
        for (Map.Entry<String, Integer> cost : offer.costs().entrySet()) {
            affordable = Math.min(affordable, SkyStacks.count(inventory, cost.getKey()) / cost.getValue());
        }
        int units = (int) Math.min(wanted, Math.min(fits, affordable));
        if (fits <= 0) {
            fail(player, "Your inventory is full!");
            return;
        }
        if (units <= 0) {
            fail(player, offer.coins() > Wallet.balance(player) ? "You don't have enough coins!" : "You don't have the items that takes!");
            return;
        }
        long coins = offer.coins() * units;
        if (coins > 0 && !Wallet.take(player, coins)) {
            fail(player, "You don't have enough coins!");
            return;
        }
        offer.costs().forEach((item, count) -> SkyStacks.take(inventory, item, count * units));
        give(player, def, offer.count() * units);
        MutableComponent line = Component.literal("You bought ").withStyle(ChatFormatting.GREEN)
                .append(Component.literal(def.name()).withColor(def.rarity().color()))
                .append(Component.literal(offer.count() * units > 1 ? " x" + Msg.number(offer.count() * units) : "").withStyle(ChatFormatting.GRAY));
        if (coins > 0) {
            line.append(Component.literal(" for ").withStyle(ChatFormatting.GREEN))
                    .append(Component.literal(Msg.number(coins) + " Coins").withStyle(ChatFormatting.GOLD));
        }
        player.sendOverlayMessage(line);
        player.level().playSound(null, player.blockPosition(), SoundEvents.NOTE_BLOCK_PLING.value(), SoundSource.PLAYERS, 0.6f, 1.6f);
    }

    /** Sells the stack in this inventory slot to the shop. */
    static void sell(ServerPlayer player, int slot) {
        Inventory inventory = player.getInventory();
        ItemStack stack = inventory.getItem(slot);
        if (stack.isEmpty()) {
            return;
        }
        long price = sellPrice(stack);
        if (price <= 0) {
            fail(player, "You can't sell that to a shop!");
            return;
        }
        ItemStack sold = stack.copy();
        inventory.setItem(slot, ItemStack.EMPTY);
        Wallet.give(player, price);
        Deque<Sale> sales = sales(player);
        sales.addFirst(new Sale(sold, price));
        while (sales.size() > BUYBACK) {
            sales.removeLast();
        }
        player.sendOverlayMessage(Component.literal("You sold ").withStyle(ChatFormatting.GREEN).append(sold.getHoverName())
                .append(Component.literal(sold.getCount() > 1 ? " x" + sold.getCount() : "").withStyle(ChatFormatting.GRAY))
                .append(Component.literal(" for ").withStyle(ChatFormatting.GREEN))
                .append(Component.literal(Msg.number(price) + " Coins").withStyle(ChatFormatting.GOLD)));
        player.level().playSound(null, player.blockPosition(), SoundEvents.EXPERIENCE_ORB_PICKUP, SoundSource.PLAYERS, 0.6f, 1.2f);
    }

    /** Buys back a recent sale (0 = the newest) for what it paid. */
    static void buyback(ServerPlayer player, int index) {
        Deque<Sale> sales = sales(player);
        if (index < 0 || index >= sales.size()) {
            return;
        }
        Sale sale = new ArrayList<>(sales).get(index);
        if (room(player.getInventory(), sale.stack()) < sale.stack().getCount()) {
            fail(player, "Your inventory is full!");
            return;
        }
        if (!Wallet.take(player, sale.price())) {
            fail(player, "You need " + Msg.number(sale.price()) + " Coins to buy that back!");
            return;
        }
        sales.remove(sale);
        player.getInventory().add(sale.stack().copy());
        player.sendOverlayMessage(Component.literal("You bought back ").withStyle(ChatFormatting.GREEN).append(sale.stack().getHoverName())
                .append(Component.literal(" for ").withStyle(ChatFormatting.GREEN))
                .append(Component.literal(Msg.number(sale.price()) + " Coins").withStyle(ChatFormatting.GOLD)));
        player.level().playSound(null, player.blockPosition(), SoundEvents.ITEM_PICKUP, SoundSource.PLAYERS, 0.6f, 1.0f);
    }

    /** How many of this item the main inventory can still take. */
    static int room(Inventory inventory, ItemStack sample) {
        int room = 0;
        for (int i = 0; i < Inventory.INVENTORY_SIZE; i++) {
            ItemStack in = inventory.getItem(i);
            if (in.isEmpty()) {
                room += sample.getMaxStackSize();
            } else if (ItemStack.isSameItemSameComponents(in, sample)) {
                room += Math.max(0, in.getMaxStackSize() - in.getCount());
            }
        }
        return room;
    }

    /** Gives {@code count} of an item, unique ones one by one. */
    private static void give(ServerPlayer player, ItemDefinition def, int count) {
        boolean unique = SkyItems.unstackable(def);
        int left = count;
        while (left > 0) {
            ItemStack stack = SkyItems.create(def, 1);
            int n = unique ? 1 : Math.min(left, stack.getMaxStackSize());
            stack.setCount(n);
            left -= n;
            player.getInventory().add(stack);
            if (!stack.isEmpty()) {
                player.drop(stack, false, net.minecraft.util.Prediction.SERVER_ONLY);
            }
        }
    }

    private static void fail(ServerPlayer player, String text) {
        player.sendOverlayMessage(Component.literal(text).withStyle(ChatFormatting.RED));
        player.level().playSound(null, player.blockPosition(), SoundEvents.VILLAGER_NO, SoundSource.PLAYERS, 0.5f, 1f);
    }

    /** {@code /sbshop}: the list of shops, {@code /sbshop <id>} opens one (admins, for testing and setting up NPCs). */
    public static void register(CommandDispatcher<CommandSourceStack> dispatcher) {
        dispatcher.register(Commands.literal("sbshop").requires(Commands.hasPermission(Commands.LEVEL_GAMEMASTERS))
                .executes(ctx -> {
                    list(ctx.getSource().getPlayerOrException());
                    return shops.size();
                })
                .then(Commands.argument("shop", StringArgumentType.word())
                        .suggests((ctx, builder) -> SharedSuggestionProvider.suggest(shops.keySet().stream().map(Identifier::getPath), builder))
                        .executes(ctx -> {
                            Shop shop = find(StringArgumentType.getString(ctx, "shop"));
                            if (shop == null) {
                                ctx.getSource().sendFailure(Component.literal("No shop called " + StringArgumentType.getString(ctx, "shop")));
                                return 0;
                            }
                            ShopMenu.open(ctx.getSource().getPlayerOrException(), shop);
                            return 1;
                        })));
        ServerPlayConnectionEvents.DISCONNECT.register((handler, server) -> forget(handler.player.getUUID()));
    }

    /** The shop list for the {@code /sbshop} command. */
    static void list(ServerPlayer player) {
        Notice.Panel panel = Notice.of(Notice.Kind.SHOP).tag("SHOPS").panel();
        shops.values().stream().map(shop -> shop.id().getPath() + " (" + shop.name() + ", " + shop.offers().size() + ")")
                .sorted().forEach(line -> panel.line(Component.literal(line).withStyle(ChatFormatting.GRAY)));
        panel.send(player, Component.literal(shops.size() + " NPC shops").withStyle(ChatFormatting.WHITE));
    }
}

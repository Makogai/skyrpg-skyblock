package com.skyrpg.skyblock.recipe;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.skyrpg.core.data.JsonDataLoader;
import com.skyrpg.core.progress.CollectionLevels;
import com.skyrpg.items.ItemDefinition;
import com.skyrpg.items.ItemRegistry;
import com.skyrpg.items.SkyStacks;
import com.skyrpg.skyblock.SkyRpgSkyblock;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.function.IntPredicate;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;

/**
 * Hypixel's crafting recipes, from {@code data/skyrpg_skyblock/skyrpg/skyblock_recipes/*.json} (generated by
 * {@code tools/skyblock/import_recipes.py}): a 3 by 3 grid of SkyBlock items with counts, what it makes, and what
 * unlocks it. The single-ingredient ones double as compacting rules: 9 Coal make a Coal Block (a Compactor's job),
 * 160 Cobblestone an Enchanted Cobblestone (a Super Compactor's). The client gets the same recipes from the server
 * ({@link RecipesPayload}) for the Recipe Book.
 */
public final class Recipes {
    public static final String DIRECTORY = "skyrpg/skyblock_recipes";

    /** One cell of a grid: a SkyBlock item and how many of it (empty cells have no item). */
    public record Cell(String item, int count) {
        public static final Cell EMPTY = new Cell("", 0);

        public boolean isEmpty() {
            return item.isEmpty();
        }
    }

    /** What unlocks a recipe: a collection tier, a slayer level, something else ({@code text}), or nothing. */
    public record Requirement(String collection, int tier, String slayer, int level, String text) {
        public static final Requirement NONE = new Requirement("", 0, "", 0, "");

        public boolean none() {
            return collection.isEmpty() && slayer.isEmpty() && text.isEmpty();
        }

        /** "Cobblestone Collection IV", "Zombie Slayer 3", or Hypixel's own words. Empty for none. */
        public String describe() {
            if (!collection.isEmpty()) {
                return CollectionLevels.requirement(collectionId(collection), tier);
            }
            if (!slayer.isEmpty()) {
                return Character.toUpperCase(slayer.charAt(0)) + slayer.substring(1) + " Slayer " + level;
            }
            return text.replaceFirst("^Requires:\\s*", "");
        }
    }

    public record Recipe(Identifier id, String output, int count, List<Cell> grid, Requirement requires, JsonObject json) {
        /** Every ingredient summed up: item -> count. */
        public Map<String, Integer> ingredients() {
            Map<String, Integer> out = new LinkedHashMap<>();
            for (Cell cell : grid) {
                if (!cell.isEmpty()) {
                    out.merge(cell.item(), cell.count(), Integer::sum);
                }
            }
            return out;
        }
    }

    /** A grid that makes {@code recipe}: how many of each grid cell one craft takes (0 for empty cells). */
    public record Match(Recipe recipe, int[] need) {
        /** How many times the grid's stacks make it. */
        public int times(List<ItemStack> grid) {
            int times = Integer.MAX_VALUE;
            for (int i = 0; i < 9; i++) {
                if (need[i] > 0) {
                    times = Math.min(times, grid.get(i).getCount() / need[i]);
                }
            }
            return times == Integer.MAX_VALUE ? 0 : times;
        }
    }

    /** Compacting {@code amount} of an item into {@code count} of {@code into}. */
    public record Compaction(String from, int amount, String into, int count) {
    }

    private static Map<Identifier, Recipe> recipes = Map.of();
    private static Map<String, List<Recipe>> byOutput = Map.of();
    /** Every single-ingredient recipe, by its ingredient. */
    private static Map<String, List<Compaction>> singles = Map.of();
    /** Recipes by the set of items they use ({@link #key}), for matching a crafting grid. */
    private static Map<String, List<Recipe>> byIngredients = Map.of();
    /** Bumped on every load, so the client's Recipe Book knows to rebuild its lists. */
    private static int version;

    private Recipes() {
    }

    public static void init() {
        JsonDataLoader.register(SkyRpgSkyblock.id("recipes"), DIRECTORY, files -> {
            replace(files);
            RecipesPayload.changed();
        });
    }

    /** Loads these recipe files, replacing what was there (the server from data, the client from the server). */
    public static void replace(Map<Identifier, JsonElement> files) {
        Map<Identifier, Recipe> loaded = new LinkedHashMap<>();
        Map<String, List<Recipe>> outputs = new LinkedHashMap<>();
        Map<String, List<Compaction>> singleRules = new LinkedHashMap<>();
        Map<String, List<Recipe>> ingredientSets = new HashMap<>();
        files.forEach((id, element) -> {
            try {
                Recipe recipe = parse(id, element.getAsJsonObject());
                loaded.put(id, recipe);
                outputs.computeIfAbsent(recipe.output(), k -> new ArrayList<>()).add(recipe);
                Map<String, Integer> ingredients = recipe.ingredients();
                ingredientSets.computeIfAbsent(key(ingredients.keySet()), k -> new ArrayList<>()).add(recipe);
                if (ingredients.size() == 1) {
                    Map.Entry<String, Integer> only = ingredients.entrySet().iterator().next();
                    singleRules.computeIfAbsent(only.getKey(), k -> new ArrayList<>())
                            .add(new Compaction(only.getKey(), only.getValue(), recipe.output(), recipe.count()));
                }
            } catch (RuntimeException e) {
                SkyRpgSkyblock.LOGGER.error("Skipping invalid recipe {}: {}", id, e.getMessage());
            }
        });
        recipes = loaded;
        byOutput = outputs;
        singles = singleRules;
        byIngredients = ingredientSets;
        version++;
        SkyRpgSkyblock.LOGGER.info("Loaded {} recipes", loaded.size());
    }

    private static Recipe parse(Identifier id, JsonObject json) {
        List<Cell> grid = new ArrayList<>();
        for (JsonElement cell : json.getAsJsonArray("grid")) {
            String text = cell.getAsString();
            if (text.isEmpty()) {
                grid.add(Cell.EMPTY);
            } else {
                int colon = text.lastIndexOf(':');
                // Ids can hold a ':' themselves ("INK_SACK:4:32"): the count is after the last one.
                grid.add(new Cell(text.substring(0, colon), Integer.parseInt(text.substring(colon + 1))));
            }
        }
        if (grid.size() != 9) {
            throw new IllegalArgumentException("a grid needs 9 cells");
        }
        Requirement requires = Requirement.NONE;
        if (json.has("requires")) {
            JsonObject r = json.getAsJsonObject("requires");
            requires = new Requirement(r.has("collection") ? r.get("collection").getAsString() : "", r.has("tier") ? r.get("tier").getAsInt() : 0,
                    r.has("slayer") ? r.get("slayer").getAsString() : "", r.has("level") ? r.get("level").getAsInt() : 0,
                    r.has("text") ? r.get("text").getAsString() : "");
        }
        return new Recipe(id, json.get("output").getAsString(), json.has("count") ? json.get("count").getAsInt() : 1, List.copyOf(grid), requires,
                json);
    }

    private static String key(Collection<String> items) {
        return String.join("|", new TreeSet<>(items));
    }

    /**
     * The recipe a crafting grid (9 stacks, rows top to bottom) makes, or null. As in vanilla, a pattern smaller than
     * 3 by 3 can sit anywhere in the grid, and mirrored; every cell needs at least the recipe's count. With several
     * matches an unlocked one wins, so the screen can still show a locked match as locked.
     */
    public static Match match(List<ItemStack> grid, Player player) {
        String[] ids = new String[9];
        Set<String> used = new HashSet<>();
        for (int i = 0; i < 9; i++) {
            ItemStack stack = grid.get(i);
            if (!stack.isEmpty()) {
                ids[i] = SkyStacks.id(stack);
                if (ids[i] == null) {
                    return null; // something that isn't a SkyBlock item
                }
                used.add(ids[i]);
            }
        }
        if (used.isEmpty()) {
            return null;
        }
        Match locked = null;
        for (Recipe recipe : byIngredients.getOrDefault(key(used), List.of())) {
            int[] need = fit(recipe, ids, grid, false);
            if (need == null) {
                need = fit(recipe, ids, grid, true);
            }
            if (need != null) {
                if (unlocked(player, recipe)) {
                    return new Match(recipe, need);
                }
                if (locked == null) {
                    locked = new Match(recipe, need);
                }
            }
        }
        return locked;
    }

    /** Lays the recipe's pattern (mirrored or not) over the grid's filled area: what each grid cell needs, or null. */
    private static int[] fit(Recipe recipe, String[] ids, List<ItemStack> grid, boolean mirror) {
        int[] r = bounds(i -> !recipe.grid().get(i).isEmpty());
        int[] g = bounds(i -> ids[i] != null);
        if (r == null || g == null || r[2] - r[0] != g[2] - g[0] || r[3] - r[1] != g[3] - g[1]) {
            return null;
        }
        int[] need = new int[9];
        for (int row = 0; row <= g[3] - g[1]; row++) {
            for (int col = 0; col <= g[2] - g[0]; col++) {
                int gi = (g[1] + row) * 3 + g[0] + col;
                int rc = mirror ? r[2] - col : r[0] + col;
                Cell cell = recipe.grid().get((r[1] + row) * 3 + rc);
                if (cell.isEmpty() != (ids[gi] == null)) {
                    return null;
                }
                if (!cell.isEmpty()) {
                    if (!cell.item().equals(ids[gi]) || grid.get(gi).getCount() < cell.count()) {
                        return null;
                    }
                    need[gi] = cell.count();
                }
            }
        }
        return need;
    }

    /** The filled cells' box as {minCol, minRow, maxCol, maxRow}, or null when none is filled. */
    private static int[] bounds(IntPredicate filled) {
        int[] box = null;
        for (int i = 0; i < 9; i++) {
            if (filled.test(i)) {
                int col = i % 3;
                int row = i / 3;
                if (box == null) {
                    box = new int[] {col, row, col, row};
                } else {
                    box[0] = Math.min(box[0], col);
                    box[1] = Math.min(box[1], row);
                    box[2] = Math.max(box[2], col);
                    box[3] = Math.max(box[3], row);
                }
            }
        }
        return box;
    }

    /** The collection a Hypixel collection id is ("INK_SACK:4" is {@code skyrpg_skyblock:ink_sack-4}). */
    public static Identifier collectionId(String hypixelId) {
        return SkyRpgSkyblock.id(hypixelId.toLowerCase(Locale.ROOT).replace(':', '-'));
    }

    /**
     * Whether the player has unlocked the recipe: no requirement, or the collection tier reached. Slayer and other
     * requirements stay locked until those systems exist. Creative players have every recipe.
     */
    public static boolean unlocked(Player player, Recipe recipe) {
        Requirement requires = recipe.requires();
        if (requires.none() || player.isCreative()) {
            return true;
        }
        if (!requires.collection().isEmpty()) {
            return CollectionLevels.tier(player, collectionId(requires.collection())) >= requires.tier();
        }
        return false;
    }

    public static Collection<Recipe> all() {
        return recipes.values();
    }

    public static Recipe get(Identifier id) {
        return recipes.get(id);
    }

    public static int version() {
        return version;
    }

    /** The recipes that make this SkyBlock item. */
    public static List<Recipe> making(String skyblockId) {
        return byOutput.getOrDefault(skyblockId, List.of());
    }

    /** Every item that has a recipe, in load order. */
    public static Collection<String> outputs() {
        return byOutput.keySet();
    }

    /**
     * The Compactor's rule for this item: 4 or 9 of it into one block (Coal into a Coal Block, Snowballs into a Snow
     * Block), or null. Other single-ingredient recipes (Cactus into Cactus Boots) aren't compactions.
     */
    public static Compaction block(String skyblockId) {
        Compaction best = null;
        for (Compaction rule : singles.getOrDefault(skyblockId, List.of())) {
            ItemDefinition into = ItemRegistry.skyblock(rule.into());
            boolean isBlock = into != null && into.item() instanceof BlockItem && !into.json().has("skin");
            if (isBlock && rule.count() == 1 && (rule.amount() == 4 || rule.amount() == 9) && !rule.into().startsWith("ENCHANTED_")
                    && (best == null || rule.amount() > best.amount())) {
                best = rule;
            }
        }
        return best;
    }

    /**
     * The Super Compactor's rule for this item: into its enchanted form (160 Cobblestone into an Enchanted
     * Cobblestone, 160 of those into the enchanted block), or null. With several (Sugar Cane makes Enchanted Sugar and
     * Enchanted Paper), the usual 160 wins.
     */
    public static Compaction enchanted(String skyblockId) {
        Compaction best = null;
        for (Compaction rule : singles.getOrDefault(skyblockId, List.of())) {
            if (rule.into().startsWith("ENCHANTED_") && rule.count() == 1 && (best == null || score(rule) > score(best))) {
                best = rule;
            }
        }
        return best;
    }

    private static int score(Compaction rule) {
        return (rule.amount() == 160 ? 1_000_000 : 0) - rule.amount();
    }
}
